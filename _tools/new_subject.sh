#!/bin/bash
# Создаёт папку предмета со всей структурой: _tools/new_subject.sh <предмет> [<предмет> ...]
cd "$(dirname "$0")/.." || exit 1
[ $# -eq 0 ] && { echo "Использование: $0 <предмет> [...]"; exit 1; }
for s in "$@"; do
  mkdir -p "$s"/{Конспект_с_пада,Материал_преподом,Аудиотранскрипция,Материал_учебника,_конспекты,_разборы,.source}
  [ -f "$s/вопросы.md" ] || printf '# Вопросы: %s\n\nПиши сюда вопросы с маркерами [?] / [??] / [док] / [почему] / [связь].\n' "$s" > "$s/вопросы.md"
  echo "+ $s"
done
if [[ " $* " == *" английский "* ]]; then
  mkdir -p английский/Домашка/{входящие,_готово}
fi
